#!/usr/bin/env node
'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const CODEX_HOME = process.env.CODEX_HOME || path.join(os.homedir(), '.codex');
const CONFIG_PATH = path.join(os.homedir(), '.config', 'win-bash', 'win-bash.json');
const LEGACY_CONFIG_PATH = path.join(CODEX_HOME, 'win-bash.json');
const RC_PATH = path.join(os.homedir(), '.niubashrc');
const LEGACY_RC_PATH = path.join(os.homedir(), '.winshrc');
const SHELL_TOOLS = new Set(['exec_command', 'functions.exec_command']);
const LOCAL_APP_DATA = process.env.LOCALAPPDATA || '';
const CANDIDATES = [
  String.raw`D:\apps\Niubash\winuxcmd\bin\bash.exe`,
  String.raw`D:\apps\Niubash\niu.exe`,
  String.raw`F:\studio\apps\Niubash\winuxcmd\bin\bash.exe`,
  LOCAL_APP_DATA ? path.join(LOCAL_APP_DATA, 'Niubash', 'winuxcmd', 'bin', 'bash.exe') : '',
  LOCAL_APP_DATA ? path.join(LOCAL_APP_DATA, 'Niubash', 'niu.exe') : '',
].filter(Boolean);

const DEFAULT_RC = [
  '# Niubash interactive rc - generated by win-bash plugin.',
  '# Edit freely with normal Niubash/bash syntax.',
  '',
  "NIU_THEME='minimal'",
  "NIU_THEME_PLUGIN='theme-minimal'",
  "NIU_PROMPT_SYMBOL='>'",
  "NIU_COMPLETION_STYLE='column'",
  'export NIU_THEME NIU_THEME_PLUGIN NIU_PROMPT_SYMBOL NIU_COMPLETION_STYLE',
  '',
  'NIU_PLUGINS=(prompt-core git common-aliases)',
  '',
  'if [ -z "${HOME:-}" ] && [ -n "${USERPROFILE:-}" ]; then',
  '  HOME="${USERPROFILE//\\\\//}"',
  '  export HOME',
  'fi',
  '',
  'if [ -z "${NIUBASH:-}" ]; then',
  '  for __niubash_bundle in "$HOME/.oh-my-niu" "$HOME/.niubash/oh-my-niu" "$HOME/.niubash/bundles/oh-my-niu"/* "$NIU_APP_BUNDLE_PATH"; do',
  '    if [ -f "$__niubash_bundle/oh-my-niu.niu" ] || [ -f "$__niubash_bundle/oh-my-niu.winux" ]; then',
  '      NIUBASH="$__niubash_bundle"',
  '      export NIUBASH',
  '      break',
  '    fi',
  '  done',
  'fi',
  '',
  '[ -f "$NIUBASH/oh-my-niu.niu" ] && . "$NIUBASH/oh-my-niu.niu"',
  '[ -f "$NIUBASH/oh-my-niu.winux" ] && . "$NIUBASH/oh-my-niu.winux"',
  'niubash_prompt_use_template "{cwd} {git_prompt}{prompt_char} " "{time} " 2>/dev/null || true',
  '',
  "alias ll='ls -la'",
  "alias la='ls -a'",
  "alias gst='git status'",
  "alias gco='git checkout'",
  "alias gl='git log --oneline --graph --decorate --all'",
  '',
].join('\n');

function normalizeShell(value) {
  return String(value || '').replace(/\//g, '\\').toLowerCase();
}

function isFile(value) {
  try { return fs.statSync(value).isFile(); } catch (_) { return false; }
}

function migrateLegacyConfig() {
  if (!fs.existsSync(LEGACY_CONFIG_PATH)) return;
  const legacy = (() => { try { return JSON.parse(fs.readFileSync(LEGACY_CONFIG_PATH, 'utf8')); } catch (_) { return {}; } })();
  if (!legacy || typeof legacy !== 'object' || !legacy.shell) { fs.rmSync(LEGACY_CONFIG_PATH, { force: true }); return; }
  const config = readConfigRaw();
  if (!config.shell) config.shell = legacy.shell;
  config.platforms = config.platforms || {};
  config.platforms.codex = true;
  fs.mkdirSync(path.dirname(CONFIG_PATH), { recursive: true });
  fs.writeFileSync(CONFIG_PATH, JSON.stringify(config, null, 2) + '\n');
  fs.rmSync(LEGACY_CONFIG_PATH, { force: true });
}

function readConfig() {
  migrateLegacyConfig();
  try { return JSON.parse(fs.readFileSync(CONFIG_PATH, 'utf8')); } catch (_) { return {}; }
}

function readConfigRaw() {
  try { return JSON.parse(fs.readFileSync(CONFIG_PATH, 'utf8')); } catch (_) { return {}; }
}

function writeConfig(shell) {
  const config = readConfigRaw();
  config.shell = shell;
  config.platforms = config.platforms || {};
  config.platforms.codex = true;
  fs.mkdirSync(path.dirname(CONFIG_PATH), { recursive: true });
  fs.writeFileSync(CONFIG_PATH, JSON.stringify(config, null, 2) + '\n');
}

function ensureDefaultRc() {
  if (fs.existsSync(RC_PATH)) return { created: false, reason: 'exists' };
  if (fs.existsSync(LEGACY_RC_PATH)) return { created: false, reason: 'legacy-exists' };
  fs.writeFileSync(RC_PATH, DEFAULT_RC, 'utf8');
  return { created: true, reason: 'created' };
}

function whereBash() {
  try {
    const out = execFileSync('where.exe', ['bash.exe'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
    return out.split(/\r?\n/).map((line) => line.trim()).filter(Boolean);
  } catch (_) {
    return [];
  }
}

function resolveBash() {
  const candidates = [];
  if (process.env.WIN_BASH_PATH) candidates.push(process.env.WIN_BASH_PATH);
  const config = readConfig();
  if (config.shell) candidates.push(config.shell);
  candidates.push(...CANDIDATES, ...whereBash().filter((value) => /niubash/i.test(value)));
  for (const candidate of candidates) {
    if (isFile(candidate)) return candidate;
  }
  return null;
}

function readStdin() {
  return new Promise((resolve) => {
    let data = '';
    process.stdin.setEncoding('utf8');
    process.stdin.on('data', (chunk) => { data += chunk; });
    process.stdin.once('end', () => resolve(data));
    process.stdin.once('error', () => resolve(''));
  });
}

function isWindowsHost() {
  return process.platform === 'win32' ||
    process.env.OS === 'Windows_NT' ||
    typeof process.env.ComSpec === 'string' ||
    typeof process.env.SystemRoot === 'string';
}

function parseToolInput(payload) {
  let input = payload && payload.tool_input;
  if (typeof input === 'string') {
    try { input = JSON.parse(input); } catch (_) { return null; }
  }
  return input && typeof input === 'object' && !Array.isArray(input) ? input : null;
}

function emitContext(eventName, context) {
  process.stdout.write(JSON.stringify({
    hookSpecificOutput: { hookEventName: eventName, additionalContext: context },
  }) + '\n');
}

function configure() {
  const shell = resolveBash();
  if (!shell) return { ok: false, shell: null, config: CONFIG_PATH, rc: RC_PATH, rc_result: null };
  writeConfig(shell);
  const rcResult = ensureDefaultRc();
  return { ok: true, shell, config: CONFIG_PATH, rc: RC_PATH, rc_result: rcResult };
}

async function main() {
  const mode = process.argv[2] || 'pre-tool-use';

  if (mode === 'resolve') {
    const shell = resolveBash();
    if (shell) writeConfig(shell);
    process.stdout.write(JSON.stringify({ shell, config: CONFIG_PATH }, null, 2) + '\n');
    process.exit(shell ? 0 : 1);
  }

  if (mode === 'doctor') {
    const result = configure();
    process.stdout.write(JSON.stringify(result, null, 2) + '\n');
    process.exit(result.ok ? 0 : 1);
  }

  if (mode === 'configure') {
    const result = configure();
    process.stdout.write(JSON.stringify(result, null, 2) + '\n');
    process.exit(result.ok ? 0 : 1);
  }

  const raw = await readStdin();
  if (!raw.trim()) return;

  if (mode === 'session-start') {
    const result = configure();
    if (result.ok) return;
    emitContext('SessionStart', `win-bash is installed but no Bash executable was found. Run the win-bash install.ps1 with -InstallerPath, -DownloadUrl, or set WIN_BASH_PATH. Config: ${CONFIG_PATH}`);
    return;
  }

  if (mode !== 'pre-tool-use') return;
  if (!isWindowsHost()) return;

  let payload;
  try { payload = JSON.parse(raw); } catch (_) { return; }
  if (!payload || payload.hook_event_name !== 'PreToolUse') return;
  if (!SHELL_TOOLS.has(String(payload.tool_name || '').toLowerCase())) return;

  const input = parseToolInput(payload);
  if (!input) return;

  const shell = resolveBash();
  if (!shell) {
    return;
  }
  if (normalizeShell(input.shell) === normalizeShell(shell)) return;

  process.stdout.write(JSON.stringify({
    hookSpecificOutput: {
      hookEventName: 'PreToolUse',
      permissionDecision: 'allow',
      updatedInput: { ...input, shell },
    },
  }) + '\n');
}

main().catch(() => {});
