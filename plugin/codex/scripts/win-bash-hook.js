function normalizeShell(value) {
  return String(value || '').replace(/\//g, '\\').toLowerCase();
}

function isFile(value) {
  try { return fs.statSync(value).isFile(); } catch (_) { return false; }
}

function migrateLegacyConfig() {
  if (!fs.existsSync(LEGACY_CONFIG_PATH)) return;
  const legacy = (() => { try { return JSON.parse(fs.readFileSync(LEGACY_CONFIG_PATH, 'utf8')); } catch (_) { return {}; } })();
  if (!legacy || typeof legacy !== 'object' || !legacy.shell) { fs.rmSync(LEGACY_CONFIG_PATH, { force: true }); return; }
  const config = readConfigRaw();
  if (!config.shell) config.shell = legacy.shell;
  config.platforms = config.platforms || {};
  config.platforms.codex = true;
  fs.mkdirSync(path.dirname(CONFIG_PATH), { recursive: true });
  fs.writeFileSync(CONFIG_PATH, JSON.stringify(config, null, 2) + '\n');
  fs.rmSync(LEGACY_CONFIG_PATH, { force: true });
}

function readConfig() {
  migrateLegacyConfig();
  try { return JSON.parse(fs.readFileSync(CONFIG_PATH, 'utf8')); } catch (_) { return {}; }
}

function readConfigRaw() {
  try { return JSON.parse(fs.readFileSync(CONFIG_PATH, 'utf8')); } catch (_) { return {}; }
}

function writeConfig(shell, paths) {
  const config = readConfigRaw();
  config.shell = shell;
  if (paths) {
    if (typeof paths.niubash_path === 'string') config.niubash_path = paths.niubash_path;
    if (typeof paths.gitbash_path === 'string') config.gitbash_path = paths.gitbash_path;
    if (typeof paths.pwsh_path === 'string') config.pwsh_path = paths.pwsh_path;
  }
  config.platforms = config.platforms || {};
  config.platforms.codex = true;
  fs.mkdirSync(path.dirname(CONFIG_PATH), { recursive: true });
  fs.writeFileSync(CONFIG_PATH, JSON.stringify(config, null, 2) + '\n');
}

// Replace an existing win-bash Git-inherit block (v1/v2/v3) inside an rc with
// the current GIT_INHERIT_RC, preserving all other user content. The block is
// delimited by the "# win-bash: inherit standard Git Bash commands" header and
// the first "unset __wb_..." terminator line. Returns the swapped text, or null
// when the rc has no win-bash Git-inherit block.
function swapGitInheritBlock(content) {
  const lines = String(content).split('\n');
  let start = -1;
  for (let i = 0; i < lines.length; i++) {
    if (lines[i].indexOf('# win-bash: inherit standard Git Bash commands') === 0) { start = i; break; }
  }
  if (start === -1) return null;
  let end = -1;
  for (let i = start + 1; i < lines.length; i++) {
    if (/^unset __wb_/.test(lines[i])) { end = i; break; }
  }
  const block = GIT_INHERIT_RC.split('\n');
  if (end === -1) return [...lines.slice(0, start), ...block].join('\n');
  return [...lines.slice(0, start), ...block, ...lines.slice(end + 1)].join('\n');
}

// Returns { created, reason } describing what happened to the rc file. When the
// rc already exists (user file or Niubash wizard output), replace any old
// win-bash Git-inherit block (v1/v2) with the current one, or append it when
// absent, so Plan B (Niubash inherits Git commands) also applies to interactive
// Niubash sessions too. Never overwrite user content.
function ensureDefaultRc() {
  if (fs.existsSync(RC_PATH)) {
    const existing = fs.readFileSync(RC_PATH, 'utf8');
    // swapGitInheritBlock below is idempotent: an already-current v3 block
    // round-trips to identical text and falls through to reason 'exists'.
    const swapped = swapGitInheritBlock(existing);
    if (swapped !== null && swapped !== existing) {
      fs.writeFileSync(RC_PATH, swapped, 'utf8');
      return { created: false, reason: 'git-inherit-upgraded' };
    }
    if (swapped === null) {
      const block = existing.endsWith('\n') ? GIT_INHERIT_RC : `\n${GIT_INHERIT_RC}`;
      fs.appendFileSync(RC_PATH, `${block}\n`, 'utf8');
      return { created: false, reason: 'git-inherit-appended' };
    }
    return { created: false, reason: 'exists' };
  }
  if (fs.existsSync(LEGACY_RC_PATH)) return { created: false, reason: 'legacy-exists' };
  fs.writeFileSync(RC_PATH, DEFAULT_RC, 'utf8');
  return { created: true, reason: 'created' };
}

function whereBash() {
  try {
    const out = execFileSync('where.exe', ['bash.exe'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
    return out.split(/\r?\n/).map((line) => line.trim()).filter(Boolean);
  } catch (_) {
    return [];
  }
}

// Whether a bare `bash` on PATH resolves to a Niubash Bash (winuxcmd). When
// true we inject the bare `bash` name so the host resolves it from PATH;
// otherwise we fall back to the absolute Niubash path (portable install).
function bareBashIsNiubash() {
  return whereBash().some((entry) => /winuxcmd[\\/](?:usr[\\/])?bin[\\/]bash\.exe$/i.test(entry));
}
function resolveBash() {
  const candidates = [];
  if (process.env.WIN_BASH_PATH) candidates.push(process.env.WIN_BASH_PATH);
  const config = readConfig();
  if (config.shell) candidates.push(config.shell);
  if (config.niubash_path) candidates.push(config.niubash_path);
  candidates.push(...CANDIDATES, ...whereBash().filter((value) => /winuxcmd[\\/]bin[\\/]bash\.exe$/i.test(value)));
  for (const candidate of candidates) {
    if (candidate && isFile(candidate)) return candidate;
  }
  return null;
}

function resolveNiubashPure() {
  const candidates = [];
  if (process.env.WIN_BASH_PATH) candidates.push(process.env.WIN_BASH_PATH);
  const config = readConfig();
  // A winuxcmd-valued config.shell is the active Niubash (not a manual override
  // to Git Bash/pwsh), so it is preferred when recording niubash_path.
  if (config.shell && /winuxcmd[\\/]bin[\\/]bash\.exe$/i.test(config.shell)) candidates.push(config.shell);
  if (config.niubash_path) candidates.push(config.niubash_path);
  candidates.push(...CANDIDATES, ...whereBash().filter((value) => /winuxcmd[\\/]bin[\\/]bash\.exe$/i.test(value)));
  for (const candidate of candidates) {
    if (candidate && isFile(candidate)) return candidate;
  }
  return null;
}
function readStdin() {
  return new Promise((resolve) => {
    let data = '';
    process.stdin.setEncoding('utf8');
    process.stdin.on('data', (chunk) => { data += chunk; });
    process.stdin.once('end', () => resolve(data));
    process.stdin.once('error', () => resolve(''));
  });
}

function isWindowsHost() {
  return process.platform === 'win32' ||
    process.env.OS === 'Windows_NT' ||
    typeof process.env.ComSpec === 'string' ||
    typeof process.env.SystemRoot === 'string';
}

function parseToolInput(payload) {
  let input = payload && payload.tool_input;
  if (typeof input === 'string') {
    try { input = JSON.parse(input); } catch (_) { return null; }
  }
  return input && typeof input === 'object' && !Array.isArray(input) ? input : null;
}

function emitContext(eventName, context) {
  process.stdout.write(JSON.stringify({
    hookSpecificOutput: { hookEventName: eventName, additionalContext: context },
  }) + '\n');
}

function configure() {
  const config = readConfig();
  // Strategy X: an existing valid shell (user manual override) wins and is
  // never overwritten. Otherwise the main shell resolves as the chain
  // Niubash -> Git Bash -> pwsh.
  let shell = (typeof config.shell === 'string' && isFile(config.shell)) ? config.shell : null;

  // Each *_path is re-resolved only when missing or no longer valid, so a
  // recorded path is kept and never repeatedly overwritten.
  const updates = {};
  const storedNiu = typeof config.niubash_path === 'string' ? config.niubash_path : '';
  const niubashValid = storedNiu && isFile(storedNiu);
  const niubash = niubashValid ? storedNiu : resolveNiubashPure();
  if (!niubashValid && niubash) updates.niubash_path = niubash;

  const storedGit = typeof config.gitbash_path === 'string' ? config.gitbash_path : '';
  const gitValid = storedGit && isFile(storedGit) && !/winuxcmd[\\/]bin[\\/]bash\.exe$/i.test(storedGit);
  const gitBash = gitValid ? storedGit : resolveGitBash();
  if (!gitValid && gitBash) updates.gitbash_path = gitBash;

  const storedPwsh = typeof config.pwsh_path === 'string' ? config.pwsh_path : '';
  const pwsh = storedPwsh || resolvePwsh();
  if (!storedPwsh && pwsh) updates.pwsh_path = pwsh;

  if (!shell) shell = niubash || gitBash || pwsh;
  if (!shell) return { ok: false, shell: null, git_bash: gitBash, pwsh, config: CONFIG_PATH, rc: RC_PATH, rc_result: null };

  const needWrite = Object.keys(updates).length > 0 || !config.platforms || !config.platforms.codex;
  if (needWrite) writeConfig(shell, updates);
  const rcResult = ensureDefaultRc();
  return { ok: true, shell, git_bash: gitBash, pwsh, config: CONFIG_PATH, rc: RC_PATH, rc_result: rcResult };
}

// ---- command routing -------------------------------------------------------

// Any occurrence of these Windows-native programs keeps the host PowerShell:
// psmux/pmux/tmux must never run inside a Bash environment (they mis-detect a
// Unix-like host and emit POSIX commands that break pwsh panes).
const WINDOWS_NATIVE_WORDS = ['psmux', 'pmux', 'tmux', 'powershell', 'pwsh'];

// First-token commands that must stay on the host PowerShell: cmd.exe builtins
// that have no standalone .exe (Niubash/bash would fail or behave differently).
// Windows shell scripts (.ps1/.bat/.cmd) also stay on the host shell. Every
// other command routes to the Niubash Bash by default.
const HOST_FIRST_TOKENS = new Set([
  'dir', 'cls', 'copy', 'del', 'ren', 'move', 'md', 'rd', 'type', 'start',
]);

// First-token commands that need Bash/POSIX semantics. They route to the
// Niubash Bash explicitly (the final classify() default routes everything else
// to Niubash too); this set documents the POSIX-first surface.
const POSIX_FIRST_TOKENS = new Set([
  'bash', 'sh', 'zsh', 'dash', 'ash', 'ksh',
  'grep', 'egrep', 'fgrep', 'rg', 'sed', 'awk', 'perl',
  'find', 'xargs', 'ls', 'cat', 'tac', 'head', 'tail', 'tee', 'tr', 'cut',
  'sort', 'uniq', 'wc', 'diff', 'patch', 'tar', 'gzip', 'gunzip', 'bzip2',
  'xz', 'zip', 'unzip', 'less', 'more', 'nl', 'od', 'paste', 'join', 'comm',
  'fold', 'fmt', 'expand', 'unexpand', 'split', 'csplit',
  'touch', 'chmod', 'chown', 'chgrp', 'ln', 'readlink', 'realpath',
  'basename', 'dirname', 'stat', 'du', 'df', 'ps', 'kill', 'pkill',
  'killall', 'top', 'free', 'uptime', 'uname', 'who', 'id', 'groups',
  'env', 'export', 'source', 'pwd', 'echo', 'printf', 'yes', 'true',
  'false', 'sleep', 'seq', 'expr', 'test', '[', 'which', 'cd', 'mkdir',
  'rmdir', 'cp', 'mv', 'rm', 'clear', 'history', 'date', 'cal', 'nproc',
  'curl', 'wget', 'openssl', 'ssh', 'scp', 'rsync',
  'make', 'cmake', 'ninja', 'git',
]);

function firstToken(cmd) {
  const match = String(cmd).trim().match(/^(\S+)/);
  return match ? match[1].toLowerCase().replace(/\.exe$/, '') : '';
}

function hasWindowsNativeWord(cmd) {
  // Match the native words only where they are being RUN as a command: at the
  // start of the line or right after a command separator (; & | ( ). Never as
  // an argument such as `grep tmux`, so POSIX pipelines stay in Niubash.
  const lower = String(cmd).toLowerCase();
  return WINDOWS_NATIVE_WORDS.some((word) => {
    const escaped = word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    return new RegExp(`(^|[;&|(]\\s*)${escaped}(\\.exe)?(\\s|$|[^a-z0-9])`).test(lower);
  });
}

// Classify a command as needing the Niubash Bash ('niubash') or staying on the
// host PowerShell ('none'). Plan B: everything routes to the Niubash Bash
// except commands that genuinely require a Windows native shell (tmux/psmux/
// pmux/powershell/pwsh, PowerShell Verb-Noun cmdlets, and cmd.exe builtins with
// no standalone .exe). Windows-native checks run first so piped PowerShell/tmux
// commands are never dragged into Bash.
function classify(cmd) {
  if (typeof cmd !== 'string' || !cmd.trim()) return 'none';
  const lower = cmd.toLowerCase();
  if (hasWindowsNativeWord(cmd)) return 'none';
  const ft = firstToken(cmd);
  if (/^[a-z]+-[a-z0-9]+$/.test(ft)) return 'none'; // PowerShell Verb-Noun cmdlet
  if (HOST_FIRST_TOKENS.has(ft)) return 'none';
  if (ft.endsWith('.ps1') || ft.endsWith('.psm1') || ft.endsWith('.psd1') || ft.endsWith('.bat') || ft.endsWith('.cmd')) return 'none';
  if (ft === 'bash') return 'niubash';
  if (POSIX_FIRST_TOKENS.has(ft)) return 'niubash';
  if (ft === '.' || ft.startsWith('./') || ft.startsWith('../') || ft.endsWith('.sh')) return 'niubash';
  if (/(\||&&|\$\(|\$\{|`|>>|>|\#\!)/.test(lower)) return 'niubash';
  return 'niubash'; // Everything else routes to the Niubash Bash (+ Git inheritance).
}

// Per-command escape hatches, parsed from a leading token and stripped before
// the command reaches the shell: WIN_BASH_SKIP=1 (never rewrite) and
// WIN_BASH_SHELL=<path> (force this shell, quote the path if it has spaces).
function parseEscapeHatches(cmd) {
  if (typeof cmd !== 'string') return { skip: false, force: null, cmd: '' };
  const trimmed = String(cmd).trimStart();
  if (!trimmed) return { skip: false, force: null, cmd: '' };
  const skipMatch = trimmed.match(/^WIN_BASH_SKIP=1([\s\S]*)$/);
  if (skipMatch) return { skip: true, force: null, cmd: skipMatch[1].trimStart() };
  const forceMatch = trimmed.match(/^WIN_BASH_SHELL=("(?:[^"]*)"|'[^']*'|\S+)([\s\S]*)$/);
  if (forceMatch) {
    let value = forceMatch[1];
    if (value.length >= 2 && value[0] === '"' && value[value.length - 1] === '"') value = value.slice(1, -1);
    if (value.length >= 2 && value[0] === "'" && value[value.length - 1] === "'") value = value.slice(1, -1);
    return { skip: false, force: value, cmd: forceMatch[2].trimStart() };
  }
  return { skip: false, force: null, cmd };
}

// Official Git for Windows install root from the registry (dynamic, no
// hardcoded install paths).
function gitRegistryInstallPath() {
  try {
    const out = execFileSync('reg.exe', ['query', 'HKLM\\SOFTWARE\\GitForWindows', '/v', 'InstallPath'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
    const match = String(out).match(/InstallPath\s+REG_SZ\s+(.+)/i);
    return match ? match[1].trim() : '';
  } catch (_) {
    return '';
  }
}

// Derive candidate Git roots from git.exe on PATH (git.exe lives at
// <root>/cmd/git.exe or <root>/bin/git.exe). Dynamic, no hardcoded roots.
function whereGitRoots() {
  try {
    const out = execFileSync('where.exe', ['git.exe'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
    const roots = [];
    for (const line of String(out).split(/\r?\n/)) {
      const match = line.trim().match(/^(.*)[\\/](?:cmd|bin)[\\/]git\.exe$/i);
      if (match) roots.push(match[1]);
    }
    return roots;
  } catch (_) {
    return [];
  }
}

// Common Git for Windows install roots, used only as a last-resort fallback
// when no Git Bash is found dynamically (PATH/registry/git.exe). A Git that is
// installed but not on PATH (Start Menu / portable) is still honored.
const GIT_FALLBACK_ROOTS = [
  String.raw`C:\Program Files\Git`,
  String.raw`C:\Program Files (x86)\Git`,
  LOCAL_APP_DATA ? path.join(LOCAL_APP_DATA, 'Programs', 'Git') : '',
].filter(Boolean);

// Resolve the standard Git Bash, never Niubash. Dynamic sources first: env
// override, bash.exe on PATH under a Git root, the official Git for Windows
// registry install path, then git.exe on PATH (root derived). Only when none
// of those find a Git Bash do we check the common install roots.
function resolveGitBash() {
  if (process.env.WIN_BASH_NO_GIT === '1') return null;
  const candidates = [];
  if (process.env.OMO_CODEX_GIT_BASH_PATH) candidates.push(process.env.OMO_CODEX_GIT_BASH_PATH);
  const cfgGit = readConfig().gitbash_path;
  if (cfgGit && isFile(cfgGit) && !/winuxcmd[\\/]bin[\\/]bash\.exe$/i.test(cfgGit)) candidates.push(cfgGit);
  candidates.push(...whereBash().filter((value) => /git[\\/]bin[\\/]bash\.exe$/i.test(value)));
  const registryRoot = gitRegistryInstallPath();
  if (registryRoot) candidates.push(path.join(registryRoot, 'bin', 'bash.exe'));
  candidates.push(...whereGitRoots().map((root) => path.join(root, 'bin', 'bash.exe')));
  candidates.push(...GIT_FALLBACK_ROOTS.map((root) => path.join(root, 'bin', 'bash.exe')));
  for (const candidate of candidates) {
    if (candidate && isFile(candidate) && !/winuxcmd[\\/]bin[\\/]bash\.exe$/i.test(candidate)) return candidate;
  }
  return null;
}

// PowerShell 7 (pwsh) is the last-resort fallback shell when neither Niubash
// nor Git Bash is available. Resolved dynamically via `where.exe pwsh.exe`,
// which also returns the runnable Microsoft Store app-execution alias (a
// reparse point that isFile() cannot read, so where.exe's resolution is
// trusted directly). Falls back to the standard Program Files install root.
// Never Windows PowerShell 5.1 (powershell.exe).
function resolvePwsh() {
  // An explicit config pwsh_path is trusted directly (a Microsoft Store alias
  // is a reparse point isFile() cannot stat, matching how where.exe output is
  // treated elsewhere).
  const cfgPwsh = readConfig().pwsh_path;
  if (cfgPwsh) return cfgPwsh;
  try {
    const out = execFileSync('where.exe', ['pwsh.exe'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
    const fromWhere = String(out).split(/\r?\n/).map((line) => line.trim()).filter(Boolean);
    if (fromWhere.length) return fromWhere[0];
  } catch (_) {}
  const fallback = String.raw`C:\Program Files\PowerShell\7\pwsh.exe`;
  return isFile(fallback) ? fallback : null;
}

// Convert a Windows path (C:\\Program Files\\Git\\usr\\bin) into the MSYS/POSIX
// form Niubash accepts in PATH (/c/Program Files/Git/usr/bin).
function toPosixPath(value) {
  const drive = String(value).match(/^([A-Za-z]):[\\/](.*)$/);
  if (!drive) return String(value).replace(/\\/g, '/');
  return `/${drive[1].toLowerCase()}/${drive[2].replace(/\\/g, '/')}`;
}

// Build the `export PATH="<git dirs>:$PATH"; ` prefix that lets Niubash inherit
// standard Git Bash commands (awk/gzip/perl/tar/sed/...). Returns '' when no
// standard Git Bash is resolvable, so Niubash still runs on its own PATH.
function buildGitPathPrefix() {
  const gitBash = resolveGitBash();
  if (!gitBash) return '';
  const gitRoot = toPosixPath(path.dirname(path.dirname(gitBash)));
  const dirs = [`${gitRoot}/usr/bin`, `${gitRoot}/bin`, `${gitRoot}/cmd`];
  return `export PATH="$PATH:${dirs.join(':')}"; `;
}


// PreToolUse injection: set updatedInput.shell to the resolved Bash (bare `bash` when it
// resolves to a Niubash Bash, otherwise the absolute path). The command is NOT
// wrapped and is left unchanged apart from escape-hatch marker stripping, so a
// POSIX-only `export PATH=...` prefix never leaks into the host PowerShell
// (Codex's exec_command hook rewrite keeps updatedInput.command but drops
// updatedInput.shell). Niubash inherits standard Git Bash commands via
// ~/.niubashrc (Plan B). Never injects additionalContext.

// Decide what the PreToolUse hook should do for one exec_command input.
// Returns { action: 'skip'|'force'|'respect'|'niubash'|'bash'|'pwsh'|'none',
// shell, cmd } where shell is the shell to inject (or null) and cmd is the
// final command. Plan B: bash/POSIX/script commands route to the Niubash Bash
// with a leading `export PATH="<git dirs>:$PATH"; ` so Niubash inherits
// standard Git Bash commands (awk/gzip/perl/tar/sed/...). When no Niubash is
// installed, Git Bash is the fallback, then PowerShell 7 (pwsh) as the
// last-resort fallback.
function decide(input) {
  const original = typeof input.command === 'string' ? input.command : (typeof input.cmd === 'string' ? input.cmd : '');
  const markers = parseEscapeHatches(original);
  if (markers.skip) return { action: 'skip', shell: null, cmd: markers.cmd };
  if (markers.force) return { action: 'force', shell: isFile(markers.force) ? markers.force : null, cmd: markers.cmd };
  if (input.shell) return { action: 'respect', shell: null, cmd: original };
  const kind = classify(markers.cmd);
  if (kind === 'niubash') {
    const niubash = resolveBash();
    if (niubash) {
      const gitBash = resolveGitBash();
      const prefix = gitBash ? buildGitPathPrefix() : '';
      const shell = bareBashIsNiubash() ? 'bash' : niubash;
      return { action: 'niubash', shell, cmd: prefix ? prefix + markers.cmd : markers.cmd };
    }
    const gitBash = resolveGitBash();
    if (gitBash) return { action: 'bash', shell: gitBash, cmd: markers.cmd };
    const pwsh = resolvePwsh();
    if (pwsh) return { action: 'pwsh', shell: pwsh, cmd: markers.cmd };
    return { action: 'none', shell: null, cmd: markers.cmd };
  }
  return { action: 'none', shell: null, cmd: markers.cmd };
}

async function main() {
  const mode = process.argv[2] || 'pre-tool-use';

  if (mode === 'resolve') {
    const shell = resolveBash();
    if (shell) writeConfig(shell);
    process.stdout.write(JSON.stringify({ shell, config: CONFIG_PATH }, null, 2) + '\n');
    process.exit(shell ? 0 : 1);
  }

  if (mode === 'doctor') {
    const result = configure();
    process.stdout.write(JSON.stringify(result, null, 2) + '\n');
    process.exit(result.ok ? 0 : 1);
  }

  if (mode === 'configure') {
    const result = configure();
    process.stdout.write(JSON.stringify(result, null, 2) + '\n');
    process.exit(result.ok ? 0 : 1);
  }

  const raw = await readStdin();
  if (!raw.trim()) return;

  if (mode === 'route') {
    let payload;
    try { payload = JSON.parse(raw); } catch (_) { payload = {}; }
    const input = payload && payload.tool_input ? payload.tool_input : payload;
    process.stdout.write(JSON.stringify(decide(input || {})) + '\n');
    return;
  }

  if (mode === 'session-start') {
    const result = configure();
    const warnings = [];
    if (!result.ok) {
      warnings.push(`win-bash could not find a Niubash Bash, so shell commands cannot route to it. Install Niubash (run "win-bash bash install") or set WIN_BASH_PATH. Config: ${CONFIG_PATH}`);
    }
    if (!resolveGitBash()) {
      warnings.push('win-bash routes shell work to the Niubash Bash, but no Git for Windows (Git Bash) was found, so Niubash cannot inherit awk/gzip/perl/tar/sed. Install Git for Windows from https://git-scm.com/downloads and restart the session; the hook picks it up automatically.');
    }
    if (!result.ok && !resolveGitBash() && !resolvePwsh()) {
      warnings.push('win-bash found neither Niubash, Git Bash, nor PowerShell 7 (pwsh), the last-resort fallback shell. Install PowerShell 7 with "winget install Microsoft.PowerShell" or from https://github.com/PowerShell/PowerShell/releases, then restart the session.');
    }
    if (warnings.length) emitContext('SessionStart', warnings.join('\n'));
    return;
  }

  if (mode !== 'pre-tool-use') return;
  if (!isWindowsHost()) return;

  let payload;
  try { payload = JSON.parse(raw); } catch (_) { return; }
  if (!payload || payload.hook_event_name !== 'PreToolUse') return;
  if (!SHELL_TOOLS.has(String(payload.tool_name || '').toLowerCase())) return;

  const input = parseToolInput(payload);
  if (!input) return;

  const decision = decide(input);
  const cmdKey = typeof input.command === 'string' ? 'command' : 'cmd';
  const original = input[cmdKey] ?? '';
  // Inject only updatedInput.shell. Codex's exec_command hook rewrite keeps
  // updatedInput.command but drops updatedInput.shell, so a POSIX-only
  // `export PATH=...` prefix would run in the host PowerShell and break. Git
  // command inheritance for Niubash comes from ~/.niubashrc (Plan B), not from
  // a per-command PATH prefix. Escape-hatch markers are still stripped here.
  const markers = parseEscapeHatches(original);
  const strippedCmd = markers.cmd || original;
  const newInput = { ...input, [cmdKey]: strippedCmd };
  const shellChanged = decision.shell && normalizeShell(decision.shell) !== normalizeShell(input.shell || '');
  if (shellChanged) newInput.shell = decision.shell;
  if (newInput[cmdKey] === original && !shellChanged) return;

  process.stdout.write(JSON.stringify({
    hookSpecificOutput: {
      hookEventName: 'PreToolUse',
      permissionDecision: 'allow',
      updatedInput: newInput,
    },
  }) + '\n');
}

main().catch(() => {});
